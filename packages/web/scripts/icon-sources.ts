// Writes `src/editor/icon-sources.ts` — who drew each icon the library offers, and the words Lucide
// files its icons under (#1087, L71).
//
// Run by hand: `pnpm --filter @byd/web exec tsx scripts/icon-sources.ts`.
//
// The icons themselves come from two pinned packages, `@iconify-json/game-icons` and
// `@iconify-json/lucide`, which the library loads behind a dynamic import. What the packages do
// not carry is what a catalog entry exists to answer (L27, E4): game-icons.net is one licence and
// thirty-odd people, and a credit has to name the person, but the package names only the project.
// The person is the directory the icon lives in in `game-icons/icons`, and the directory is the
// name `license.txt` gives — so both are read here, and an icon whose author cannot be stated is
// left out rather than credited to a guess. Lucide is one licence and one name for all of it, so
// it needs no such table; its keywords are read from `lucide-static`, because a search by name
// alone finds a heart under «heart» and not under «love».
import { readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { join } from 'node:path'

const require = createRequire(import.meta.url)
const GAME_ICONS = 'https://api.github.com/repos/game-icons/icons'
const LICENCE_TXT = 'https://raw.githubusercontent.com/game-icons/icons/master/license.txt'
const LUCIDE_TAGS = 'https://cdn.jsdelivr.net/npm/lucide-static@latest/tags.json'
// A directory whose name `license.txt` spells differently; the rest agree once spaces and case go.
const ALIAS: Record<string, string> = { lucasms: 'lucas' }

const names = (pkg: string): string[] => Object.keys((JSON.parse(readFileSync(require.resolve(`${pkg}/icons.json`), 'utf8')) as { icons: Record<string, unknown> }).icons)
const key = (s: string): string => s.toLowerCase().replace(/[^a-z0-9]/g, '')

// `- Lorc, http://…` or `- Zeromancer - CC0`: the contributor, and whether they gave theirs away.
const people = new Map<string, { by: string; licence: string }>()
for (const line of (await (await fetch(LICENCE_TXT)).text()).split('\n')) {
  const [, who, cc0] = /^- ([^,]+?)(?:,\s*\S+)?(\s+-\s+CC0)?\s*$/.exec(line.trim()) ?? []
  if (who) people.set(key(who), { by: who.trim(), licence: cc0 ? 'CC0-1.0' : 'CC-BY-3.0' })
}

const head = (await (await fetch(`${GAME_ICONS}/commits/master`)).json()) as { sha: string }
const tree = (await (await fetch(`${GAME_ICONS}/git/trees/${head.sha}?recursive=1`)).json()) as { tree: { path: string }[]; truncated: boolean }
if (tree.truncated) throw new Error('game-icons/icons came back truncated')
const dirsOf = new Map<string, Set<string>>()
for (const { path } of tree.tree) {
  const [, dir, name] = /^([^/]+)\/(?:.*\/)?([^/]+)\.svg$/.exec(path) ?? []
  if (!dir || !name) continue
  dirsOf.set(name, (dirsOf.get(name) ?? new Set<string>()).add(dir))
}

const authors: { by: string; licence: string }[] = []
const authorIndex = new Map<string, number>()
const gameLines: string[] = []
const lost: { name: string; why: string }[] = []
for (const name of names('@iconify-json/game-icons').sort()) {
  const dirs = [...(dirsOf.get(name) ?? [])]
  const [dir] = dirs
  // Two people drew an icon by this name, and the package holds one of them: which one is not
  // something the package says, so neither is claimed.
  if (dir === undefined || dirs.length > 1) {
    lost.push({ name, why: dir === undefined ? 'not in game-icons/icons' : `drawn by ${dirs.join(' and ')}` })
    continue
  }
  const person = people.get(ALIAS[dir] ?? key(dir))
  if (!person) {
    lost.push({ name, why: `${dir} is not named in license.txt` })
    continue
  }
  let i = authorIndex.get(person.by)
  if (i === undefined) {
    i = authors.push(person) - 1
    authorIndex.set(person.by, i)
  }
  gameLines.push(`${name}|${i}`)
}

const tags = (await (await fetch(LUCIDE_TAGS)).json()) as Record<string, string[]>
// Only words a person types: a tag with characters the line format uses is dropped.
const lucideLines = names('@iconify-json/lucide')
  .sort()
  .flatMap((name) => {
    const words = (tags[name] ?? []).map((w) => w.toLowerCase()).filter((w) => /^[a-z0-9][a-z0-9 '-]*$/.test(w))
    return words.length > 0 ? [`${name}|${words.join(',')}`] : []
  })

const generated = new Date().toISOString().slice(0, 10)
const out = `// GENERATED by scripts/icon-sources.ts — do not edit by hand.
//
// What the two icon packages do not say about themselves (#1087, L71): who drew each game icon,
// under which licence, and the words Lucide files its icons under. Read from game-icons/icons at
// ${head.sha.slice(0, 7)} and lucide-static on ${generated}. An icon of \`@iconify-json/game-icons\` that is not
// listed here has no author that could be stated, and the library does not offer it.
//
// Loaded only behind the library's dynamic import, with the packages themselves, so none of it is
// on the editor's first paint.
//
// The day this file was written, so its age can be read without running anything.
// \`icon-catalog.test.ts\` goes red six months after it and names the command that fixes it, as the
// font list's does (#370).
export const ICON_SOURCES_GENERATED = '${generated}'

// Index → who, and the licence they publish under.
export const GAME_ICON_AUTHORS: readonly { by: string; licence: string }[] = ${JSON.stringify(authors)}

// One icon per line, \`name|author\`, the author an index into the list above.
export const GAME_ICONS_BY = \`${gameLines.join('\n')}\`

// One icon per line, \`name|word,word\`. An icon without words is searched by its name.
export const LUCIDE_WORDS = \`${lucideLines.join('\n')}\`
`
writeFileSync(join(import.meta.dirname, '..', 'src', 'editor', 'icon-sources.ts'), out)
// What was written goes on stdout; what was *lost* goes on stderr, one per line and never abridged,
// as the font script does (#370): a list that shrinks quietly is the failure worth seeing.
console.log(`${gameLines.length} game icons by ${authors.length} people and ${lucideLines.length} Lucide keyword lines written to src/editor/icon-sources.ts, stamped ${generated}`)
console.error(`${lost.length} game icons left out for want of an author that could be stated:`)
for (const { name, why } of lost) console.error(`  ${name} — ${why}`)
